"""Analysis for the resubmission arms (B1-B6 + pixel control, B4 scene graphs,
B5 light stacks): accuracy, parse rate, degenerate-output count, and paired
21-cluster bootstrap contrasts (B=20000, seed 20260809, percentile CI) against
(i) the re-run pixel control of the same scale, (ii) the archived pixel arm,
(iii) the archived serialized system D0. Per-family deltas vs the re-run control.
Writes b_arms_results.md + b_arms_results.json. Re-run as arms complete.
"""
import csv, glob, json, re
from pathlib import Path
import numpy as np, pandas as pd

LV = Path(__file__).resolve().parents[2]  # repository root
HERE = Path(__file__).resolve().parent
B, SEED = 20000, 20260809
FAM = {"counting": "counting", "direction": "direction", "nearest_class": "nearest-class",
       "nearest_dist": "nearest-distance", "path_object": "path-object"}

arch = pd.read_csv(LV / "results/exp3_predictions/predictions3_cf_v2.csv")
arch = {arm: g.set_index("question_id")[["sequence_id", "correct"]] for arm, g in arch.groupby("arm")}


def load_jsonl(p):
    rs = [json.loads(l) for l in open(p, encoding="utf-8")]
    df = pd.DataFrame(rs)
    # per-row re.match: pandas >= 3 string columns (pyarrow/RE2) reject the back-reference
    df["degenerate"] = df["raw_head"].astype(str).map(lambda s: bool(re.match(r"^(\d)\1{3,}", s)))
    df["parsed"] = df["pred"].notna()
    return df.set_index("qa_id")


def boot(diff, seq):
    rng = np.random.default_rng(SEED)
    g = pd.DataFrame({"d": diff, "s": seq}).groupby("s")["d"].agg(["sum", "size"])
    sums, ns = g["sum"].values, g["size"].values
    idx = rng.integers(0, len(g), size=(B, len(g)))
    est = sums[idx].sum(1) / ns[idx].sum(1)
    lo, hi = np.percentile(est, [2.5, 97.5])
    return float(diff.mean()), float(lo), float(hi), int(len(diff))


def contrast(a, b):
    """a, b: Series of correct indexed by qa_id (0/1); paired on the intersection."""
    common = a.index.intersection(b.index)
    seq = arch["D0_7b"].loc[common, "sequence_id"]
    d, lo, hi, n = boot((a.loc[common].astype(float) - b.loc[common].astype(float)).values, seq.values)
    star = "*" if (lo > 0 or hi < 0) else ""
    return {"delta": d, "lo": lo, "hi": hi, "n": n, "star": star, "txt": f"{d:+.4f} [{lo:+.4f}, {hi:+.4f}]{star}"}


arms = {}
for p in sorted(glob.glob(str(LV / "exp_rev1/b123_vlm_aids/*/*__clean__forced.jsonl"))):
    name = Path(p).parent.name
    if name.startswith("diag"):
        continue
    arms[f"b123/{name}"] = load_jsonl(p)
for p in sorted(glob.glob(str(LV / "exp_rev1/b4_scenegraph/*/state_typed__clean__forced.jsonl"))):
    arms[f"b4/{Path(p).parent.name}"] = load_jsonl(p)
for p in sorted(glob.glob(str(LV / "exp_rev1/b5_light/infer/*/state_typed__clean__forced.jsonl"))):
    arms[f"b5/{Path(p).parent.name}"] = load_jsonl(p)
for p in sorted(glob.glob(str(LV / "exp_rev1/b6_rfdetr/infer/*/state_typed__clean__forced.jsonl"))):
    arms[f"b6/{Path(p).parent.name}"] = load_jsonl(p)

out, lines = {}, ["# Resubmission arms (auto-generated by analysis/b_arms_analysis.py)\n",
                   "| arm | n | acc | parse | degenerate | vs re-run pixel (same scale) | vs archived pixel | vs archived D0 |", "|---|---|---|---|---|---|---|---|"]
for name, df in arms.items():
    scale = "7b" if "7b" in name else "3b"
    ctrl_key = f"b123/pixel_{scale}"
    row = {"n": int(len(df)), "acc": float(df["correct"].mean()), "parse": float(df["parsed"].mean()),
           "degenerate": int(df["degenerate"].sum()), "complete": bool(len(df) >= 1328)}
    c = df["correct"].astype(int)
    row["vs_rerun_pixel"] = contrast(c, arms[ctrl_key]["correct"].astype(int)) if ctrl_key in arms and name != ctrl_key else None
    row["vs_arch_pixel"] = contrast(c, arch[f"PIXEL_{scale}"]["correct"])
    row["vs_arch_D0"] = contrast(c, arch[f"D0_{scale}"]["correct"])
    if row["vs_rerun_pixel"]:
        fam = {}
        for f, lab in FAM.items():
            sub = df[df["category"] == f]
            fam[lab] = contrast(sub["correct"].astype(int), arms[ctrl_key]["correct"].astype(int))["txt"] if len(sub) else "-"
        row["per_family_vs_rerun_pixel"] = fam
    out[name] = row
    lines.append(f"| {name} | {row['n']} | {row['acc']:.4f} | {row['parse']:.4f} | {row['degenerate']} | "
                 f"{row['vs_rerun_pixel']['txt'] if row['vs_rerun_pixel'] else '(control)'} | {row['vs_arch_pixel']['txt']} | {row['vs_arch_D0']['txt']} |")
lines.append("\nPer-family deltas vs the re-run pixel control:")
for name, row in out.items():
    if row.get("per_family_vs_rerun_pixel"):
        lines.append(f"- {name}: " + "; ".join(f"{k} {v}" for k, v in row["per_family_vs_rerun_pixel"].items()))
(HERE / "b_arms_results.md").write_text("\n".join(lines), encoding="utf-8")
json.dump(out, open(HERE / "b_arms_results.json", "w"), indent=1)
print("\n".join(lines))
